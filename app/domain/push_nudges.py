def _pool(attempts: int) -> tuple[str, ...]:
    # Only two tiers: gentle first, lightly cheeky after. Cards are now dropped
    # after a few ignores (PUSH_MAX_ATTEMPTS), so the old "dramatic" guilt-trip
    # pool ("могу заблокировать", "приходить во снах") is gone — it literally
    # trained users to block the bot.
    return GENTLE if attempts <= 1 else CHEEKY


def nudge_line(attempts: int, rng: random.Random | None = None) -> str:
    """A nudge to prepend to a re-pushed (ignored) card. `attempts` is how many
    times this same card has been re-sent (1 = first nudge)."""
    n = max(1, attempts)
    chooser = rng.choice if rng is not None else random.choice
    phrase = chooser(_pool(n))
    return f"{phrase}\n<i>повтор №{n}</i>"
